/**
 * Добавляет 3–4 плейсхолдера для будущих фото после H2-заголовков.
 * Реальные изображения будут добавлены позже редакцией через админ-панель.
 */
function withImagePlaceholders(blocks: ArticleBlock[]): ArticleBlock[] {
  const h2Indexes = blocks
    .map((b, i) => (b.type === "h2" ? i : -1))
    .filter((i) => i !== -1);

  if (h2Indexes.length === 0) return blocks;

  const targetCount = Math.min(4, Math.max(3, h2Indexes.length));
  const step = Math.max(1, Math.floor(h2Indexes.length / targetCount));
  const chosen = h2Indexes.filter((_, idx) => idx % step === 0).slice(0, targetCount);

  const result: ArticleBlock[] = [];
  blocks.forEach((block, i) => {
    result.push(block);
    if (chosen.includes(i) && block.type === "h2") {
      result.push({
        type: "imagePlaceholder",
        caption: block.text.toLowerCase(),
      });
    }
  });
  return result;
}

export function getArticleBySlug(slug: string): ArticleData | undefined {
  const article = ARTICLES.find((a) => a.slug === slug);
  if (!article) return undefined;
  return { ...article, blocks: withImagePlaceholders(article.blocks) };
}

export function getAllSlugs(): string[] {
  return ARTICLES.map((a) => a.slug);
}

const ARTICLES_PER_PAGE = 6;

export function getArticlesPage(page: number) {
  const totalPages = Math.max(1, Math.ceil(ARTICLES.length / ARTICLES_PER_PAGE));
  const safePage = Math.min(Math.max(1, page), totalPages);
  const start = (safePage - 1) * ARTICLES_PER_PAGE;
  const items = ARTICLES.slice(start, start + ARTICLES_PER_PAGE);
  return { items, currentPage: safePage, totalPages };
}

/** Форматирует дату-заглушку в читаемый русский формат */
export function formatArticleDate(iso: string): string {
  const date = new Date(iso);
  return date.toLocaleDateString("ru-RU", {
    day: "numeric",
    month: "long",
    year: "numeric",
  });
}
