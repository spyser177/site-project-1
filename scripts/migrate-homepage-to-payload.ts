async function main() {
  console.log("=== Миграция блоков главной страницы (advantages/faq/reviews) -> Payload CMS ===");

  const payload = await getPayload({ config: configPromise });

  const current = await payload.findGlobal({ slug: "home-page" });

  await payload.updateGlobal({
    slug: "home-page",
    data: {
      ...current,
      advantages,
      faq,
      reviews,
    },
  });

  console.log(`  ✔ Обновлён global home-page: advantages (${advantages.length}), faq (${faq.length}), reviews (${reviews.length})`);
  console.log("\n=== Миграция завершена успешно ===");
}

main()
  .catch((error) => {
    console.error("✖ Ошибка миграции:", error);
    process.exitCode = 1;
  })
  .finally(() => {
    process.exit(process.exitCode ?? 0);
  });
